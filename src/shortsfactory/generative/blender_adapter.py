"""Blender Engine adapter.

This module turns a unified :class:`AnimationPlan` into a self-contained
Blender Python script and runs it **if** a Blender executable is available.

Blender is an optional local dependency.  When it is absent the adapter reports
``available=False`` and raises :class:`BlenderUnavailable`; the engine
dispatcher falls back to the built-in 2D Animation Engine instead.  The
generated script is still produced (``build_blender_script``) so the 3D
pipeline is fully inspectable even without Blender installed.
"""

from __future__ import annotations

import os
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .animation_plan import AnimationPlan

#: Environment variable that can point at a Blender executable.
BLENDER_ENV = "BLENDER_EXECUTABLE"


class BlenderUnavailable(RuntimeError):
    """Raised when Blender is required but not installed."""


@dataclass
class BlenderResult:
    status: str  # OK | PARTIAL | FAILED
    engine: str = "blender"
    video: str = ""
    contact_sheet: str = ""
    script: str = ""
    render_dir: str = ""
    notes: list[str] = field(default_factory=list)
    error: str = ""


def blender_executable() -> str | None:
    """Return the Blender executable path or None when it is unavailable.

    Resolution order: ``BLENDER_EXECUTABLE`` env var, then ``blender`` on PATH,
    then common default install locations on Windows.
    """
    env_val = os.environ.get(BLENDER_ENV, "").strip()
    if env_val:
        return env_val
    found = shutil.which("blender")
    if found:
        return found
    candidates = [
        Path(os.environ.get("ProgramFiles", "C:/Program Files"))
        / "Blender Foundation",
        Path(os.environ.get("ProgramFiles(x86)", "C:/Program Files (x86)"))
        / "Blender Foundation",
    ]
    for root in candidates:
        if root.exists():
            for version_dir in sorted(root.glob("Blender*"), reverse=True):
                exe = version_dir / "blender.exe"
                if exe.exists():
                    return str(exe)
    return None


def blender_available() -> bool:
    return blender_executable() is not None


def _escape_py(value: Any) -> str:
    """Render a Python literal (supports dict/list/str/float/int)."""
    if isinstance(value, str):
        return repr(value)
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_escape_py(v) for v in value) + "]"
    if isinstance(value, dict):
        items = ", ".join(f"{_escape_py(k)}: {_escape_py(v)}" for k, v in value.items())
        return "{" + items + "}"
    raise TypeError(f"Неподдерживаемый тип для генерации скрипта: {type(value)}")


def build_blender_script(plan: AnimationPlan, out_dir: Path, *, fps: int = 30) -> Path:
    """Write a self-contained Blender Python script that renders the plan.

    The script builds a stylised humanoid rig (primitive meshes parented to an
    armature with FK bones), a ground plane, a glowing stone object, an action
    library (idle/walk/crouch/pickup/react/joy) and camera keyframes, then
    renders an image sequence which is encoded to an MP4 with FFmpeg.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    script_path = out_dir / f"render_{plan.scene_id}.py"

    actions = [a.to_dict() for a in plan.actions]
    camera = [k.to_dict() for k in plan.camera]

    width = int(plan.width)
    height = int(plan.height)
    duration = float(plan.duration)

    actions_repr = repr(actions)
    camera_repr = repr(camera)

    body = """# Auto-generated by ShortsFactory Blender adapter (plan: __PACK__).
# This script builds a stylised rigged humanoid, keyframes a timeline of
# actions, and renders a vertical MP4.
import bpy, math, subprocess, sys, os
from pathlib import Path

OUT = Path(r"__OUT__")
VIDEO = OUT / "final.mp4"
FRAMES_DIR = OUT / "frames"
FRAMES_DIR.mkdir(parents=True, exist_ok=True)
FPS = __FPS__
WIDTH = __WIDTH__
HEIGHT = __HEIGHT__
DURATION = __DURATION__

# ----------------------------------------------------------------- cleanup
bpy.ops.wm.read_factory_settings(use_empty=True)

# ----------------------------------------------------------------- scene
bpy.context.scene.render.engine = 'BLENDER_EEVEE_NEXT' if hasattr(bpy.types, 'BLENDER_EEVEE_NEXT') else 'BLENDER_EEVEE'
bpy.context.scene.render.image_settings.file_format = 'PNG'
bpy.context.scene.render.resolution_x = WIDTH
bpy.context.scene.render.resolution_y = HEIGHT
bpy.context.scene.render.fps = FPS
bpy.context.scene.frame_start = 1
bpy.context.scene.frame_end = max(1, int(round(DURATION * FPS)))
bpy.context.scene.render.filepath = str(FRAMES_DIR / "frame_")

# world background (twilight)
world = bpy.data.worlds.new("Twilight")
world.use_nodes = True
bg = world.node_tree.nodes.get("Background")
if bg:
    bg.inputs[0].default_value = (0.09, 0.08, 0.16, 1.0)
    bg.inputs[1].default_value = 0.6
bpy.context.scene.world = world

# ground plane
bpy.ops.mesh.primitive_plane_add(size=6.0, location=(0, 0, 0))
ground = bpy.context.active_object
ground.name = "Ground"
mat = bpy.data.materials.new("GroundMat")
mat.use_nodes = True
bsdf = mat.node_tree.nodes.get("Principled BSDF")
if bsdf:
    bsdf.inputs[0].default_value = (0.10, 0.12, 0.11, 1.0)
    bsdf.inputs[9].default_value = 0.2
ground.data.materials.append(mat)

# glowing stone
bpy.ops.mesh.primitive_uv_sphere_add(radius=0.22, location=(0.6, 0.0, 0.22))
stone = bpy.context.active_object
stone.name = "Stone"
smat = bpy.data.materials.new("StoneMat")
smat.use_nodes = True
sdf = smat.node_tree.nodes.get("Principled BSDF")
if sdf:
    sdf.inputs[0].default_value = (0.44, 0.90, 0.63, 1.0)
    sdf.inputs[9].default_value = 1.0
    sdf.inputs[20].default_value = 2.0
stone.data.materials.append(smat)

# ----------------------------------------------------------------- humanoid rig
def make_limb(name, parent, x, z, length, radius, color):
    bpy.ops.mesh.primitive_cylinder_add(radius=radius, depth=length, location=(x, 0, z))
    limb = bpy.context.active_object
    limb.name = name
    lm = bpy.data.materials.new(name + "Mat")
    lm.use_nodes = True
    ldf = lm.node_tree.nodes.get("Principled BSDF")
    if ldf:
        ldf.inputs[0].default_value = color
    limb.data.materials.append(lm)
    limb.parent = parent
    return limb

# simple FK-style hierarchy of empties acting as a skeleton
root = bpy.data.objects.new("MayaRoot", None)
bpy.context.collection.objects.link(root)
root.location = (0.0, 0.0, 0.0)
torso = bpy.data.objects.new("Torso", None)
bpy.context.collection.objects.link(torso)
torso.parent = root
torso.location = (0.0, 0.0, 1.15)
head = bpy.data.objects.new("Head", None)
bpy.context.collection.objects.link(head)
head.parent = torso
head.location = (0.0, 0.0, 0.45)
bpy.ops.mesh.primitive_uv_sphere_add(radius=0.24, location=head.location)
head_mesh = bpy.context.active_object
head_mesh.name = "HeadMesh"
head_mesh.parent = head
hm = bpy.data.materials.new("HeadMat")
hm.use_nodes = True
hdf = hm.node_tree.nodes.get("Principled BSDF")
if hdf:
    hdf.inputs[0].default_value = (0.86, 0.76, 0.68, 1.0)
head_mesh.data.materials.append(hm)

arm_l = make_limb("ArmL", torso, -0.55, 1.02, 0.9, 0.09, (0.12, 0.32, 0.34, 1.0))
arm_r = make_limb("ArmR", torso, 0.55, 1.02, 0.9, 0.09, (0.12, 0.32, 0.34, 1.0))
leg_l = make_limb("LegL", root, -0.28, 0.55, 1.1, 0.12, (0.10, 0.12, 0.16, 1.0))
leg_r = make_limb("LegR", root, 0.28, 0.55, 1.1, 0.12, (0.10, 0.12, 0.16, 1.0))
# torso mesh
bpy.ops.mesh.primitive_cylinder_add(radius=0.34, depth=1.1, location=(0, 0, 1.15))
torso_mesh = bpy.context.active_object
torso_mesh.name = "TorsoMesh"
torso_mesh.parent = torso
tm = bpy.data.materials.new("TorsoMat")
tm.use_nodes = True
tdf = tm.node_tree.nodes.get("Principled BSDF")
if tdf:
    tdf.inputs[0].default_value = (0.10, 0.55, 0.45, 1.0)
torso_mesh.data.materials.append(tm)
stone.parent = arm_r

def set_action(action_name, start, duration, intensity=1.0):
    f0 = int(round((start) * FPS)) + 1
    f1 = int(round((start + duration) * FPS)) + 1
    f1 = max(f1, f0 + 1)
    a = {'idle': 0.0, 'walk': 0.0, 'crouch': 0.0,
         'pickup': 0.0, 'react': 0.0, 'joy': 0.0}
    a[action_name] = intensity
    for obj in (root, torso, head, arm_l, arm_r, leg_l, leg_r):
        for i in range(3):
            obj.rotation_euler[i] = 0.0
            obj.keyframe_insert(data_path="rotation_euler", frame=f0)
    if action_name == 'walk':
        for f in range(f0, f1, max(1, int(FPS * 0.25))):
            u = (f - f0) / max(1, f1 - f0)
            swing = math.sin(u * 6.2832 * 1.5)
            arm_l.rotation_euler[0] = 0.5 * swing
            arm_r.rotation_euler[0] = -0.5 * swing
            leg_l.rotation_euler[0] = 0.6 * swing
            leg_r.rotation_euler[0] = -0.6 * swing
            root.location[0] = -0.35 + 1.0 * u
            for obj in (arm_l, arm_r, leg_l, leg_r):
                obj.keyframe_insert(data_path="rotation_euler", frame=f)
            root.keyframe_insert(data_path="location", frame=f)
    elif action_name == 'crouch':
        root.location[2] = 0.0
        root.keyframe_insert(data_path="location", frame=f0)
        root.location[2] = -0.55
        root.keyframe_insert(data_path="location", frame=f1)
    elif action_name == 'pickup':
        root.location[2] = -0.55
        root.keyframe_insert(data_path="location", frame=f0)
        arm_r.rotation_euler[0] = -1.8
        arm_r.keyframe_insert(data_path="rotation_euler", frame=f1)
    elif action_name == 'react':
        head.rotation_euler[2] = 0.5
        head.keyframe_insert(data_path="rotation_euler", frame=f1)
        root.location[2] = 0.25
        root.keyframe_insert(data_path="location", frame=f1)

# apply authored action timeline
for a in __ACTIONS__:
    set_action(a.get("action", "idle"), a.get("start", 0.0), a.get("duration", 1.0),
               float(a.get("params", {}).get("intensity", 1.0)))

# ----------------------------------------------------------------- camera
cam = bpy.data.cameras.new("Cam")
cam_obj = bpy.data.objects.new("Camera", cam)
bpy.context.collection.objects.link(cam_obj)
bpy.context.scene.camera = cam_obj
# map stage-normalised x/y (0..1) into eye space, zoom -> dolly/focal
for k in __CAMERA__:
    f = int(round(k["t"] * FPS)) + 1
    x = (float(k.get("x", 0.5)) - 0.5) * 4.0
    z = 0.8 + float(k.get("y", 0.5)) * 1.2
    zoom = float(k.get("zoom", 1.0))
    cam_obj.location = (x, -6.0 / zoom, z)
    cam_obj.keyframe_insert(data_path="location", frame=f)

bpy.context.scene.render.image_settings.file_format = 'PNG'
bpy.ops.render.render(animation=True)

# encode with ffmpeg
ffmpeg = os.environ.get("FFMPEG_BIN", "ffmpeg")
seq = str(FRAMES_DIR / "frame_%04d.png")
subprocess.run([ffmpeg, "-y", "-framerate", str(FPS), "-i", seq,
                "-vf", f"scale={WIDTH}:{HEIGHT}",
                "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18",
                str(VIDEO)], check=True)
print("BLENDER_OK", VIDEO)
"""
    body = (
        body.replace("__PACK__", str(plan.scene_id))
        .replace("__OUT__", out_dir.as_posix())
        .replace("__FPS__", str(int(fps)))
        .replace("__WIDTH__", str(width))
        .replace("__HEIGHT__", str(height))
        .replace("__DURATION__", repr(duration))
        .replace("__ACTIONS__", actions_repr)
        .replace("__CAMERA__", camera_repr)
    )
    script_path.write_text(body, encoding="utf-8")
    return script_path


def render_blender(plan: AnimationPlan, out_dir: Path, *, script: Path | None = None) -> BlenderResult:
    """Run the Blender engine for a plan (raises if Blender is unavailable)."""
    exe = blender_executable()
    if not exe:
        raise BlenderUnavailable(
            "Blender не установлен. Установите Blender или используйте "
            "procedural/auto (Animation Engine)."
        )
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    script_path = script or build_blender_script(plan, out_dir)
    import subprocess as sp
    proc = sp.run(
        [exe, "--background", "--python", str(script_path)],
        capture_output=True,
        text=True,
        timeout=1800,
    )
    video = out_dir / "final.mp4"
    if proc.returncode != 0 or not video.exists():
        return BlenderResult(
            status="FAILED",
            script=str(script_path),
            render_dir=str(out_dir),
            notes=["Blender-рендер завершился с ошибкой."],
            error=(proc.stderr or "")[-500:],
        )
    return BlenderResult(
        status="OK",
        video=video.as_posix(),
        script=str(script_path),
        render_dir=str(out_dir),
        notes=["Трёхмерный рендер выполнен через Blender."],
    )
