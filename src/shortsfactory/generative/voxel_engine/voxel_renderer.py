def build_voxel_script(plan: AnimationPlan, out_dir: str | Path, shots: tuple | None = None) -> Path:
    """Write and return the generated Blender script path for ``plan``."""
    ensure_voxel_plan(plan)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    script_path = out_dir / f"render_voxel_{plan.scene_id}.py"

    hero = plan.characters[0] if plan.characters else None
    hero_x = _sx(hero.x) if hero else 0.0
    hero_y = _sy(hero.y) if hero else 3.0

    # Pickup action start (for the grab phase) if present.
    pickup_start = next(
        (float(a.start) for a in plan.actions if a.action == "pickup"), None
    )

    body = (
        _HEADER
        .replace("__PACK__", str(plan.scene_id))
        .replace("__OUT__", out_dir.resolve().as_posix())
        .replace("__FPS__", str(int(plan.fps)))
        .replace("__WIDTH__", str(int(plan.width)))
        .replace("__HEIGHT__", str(int(plan.height)))
        .replace("__DURATION__", repr(float(plan.duration)))
        .replace("__PALETTE__", _palette_source())
        .replace("__MATERIALS__", material_source())
        .replace("__SCENE__", build_scene_source(seed=plan.seed))
        .replace("__HERO__", build_hero_source(px=hero_x, py=hero_y))
        .replace("__OBJECTS__", interaction_source(plan.objects, plan.events, plan.fps, pickup_start))
        .replace("__ANIMATION__", action_sequence_source(plan.actions, plan.fps, (hero_x, hero_y)))
        .replace("__CAMERA__", camera_source(plan.camera, plan.fps, hero_x, hero_y, shots))
    )
    script_path.write_text(body, encoding="utf-8")
    return script_path


def render_voxel(plan: AnimationPlan, out_dir: str | Path) -> VoxelRenderResult:
    """Run the voxel engine for a plan (raises if Blender is unavailable)."""
    exe = blender_executable()
    if not exe:
        return VoxelRenderResult(
            status="PARTIAL",
            notes=["Движок voxel запрошен, но Blender не найден. Проверьте PATH или BLENDER_EXECUTABLE."],
        )
    try:
        script_path = build_voxel_script(plan, out_dir)
    except PlanError as exc:
        return VoxelRenderResult(status="FAILED", error=str(exc), notes=[f"Валидация плана не пройдена: {exc}"])
    out_dir = Path(out_dir)
    video = out_dir / "final.mp4"
    try:
        proc = subprocess.run(
            [exe, "--background", "--python", str(script_path)],
            capture_output=True,
            text=True,
            timeout=3600,
        )
    except FileNotFoundError:
        return VoxelRenderResult(status="PARTIAL", blender_script=str(script_path),
                                 notes=["Blender исполняемый файл не найден."])
    except subprocess.TimeoutExpired:
        return VoxelRenderResult(status="FAILED", blender_script=str(script_path),
                                 notes=["Blender-рендер превысил таймаут."], error="timeout")
    if proc.returncode != 0 or not video.exists():
        err = (proc.stderr or "")[-800:]
        return VoxelRenderResult(
            status="FAILED",
            blender_script=str(script_path),
            render_dir=str(out_dir),
            notes=["Voxel-рендер завершился с ошибкой (см. error)."],
            error=err,
        )
    return VoxelRenderResult(
        status="OK",
        video=video.as_posix(),
        blender_script=str(script_path),
        render_dir=str(out_dir),
        notes=["Кубический 3D-рендер выполнен через Blender (voxel)."],
    )
